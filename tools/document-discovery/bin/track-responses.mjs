#!/usr/bin/env node
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import {
  buildResponseTrackerModel,
  formatResponseTrackerSummary,
  runResponseTrackerConsole,
  writeResponseTrackerExports,
} from "../response-tracker/response-tracker.mjs";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const TOOL_ROOT = path.resolve(__dirname, "..");

function parseArgs(argv) {
  const args = {
    interactive: process.stdin.isTTY,
  };

  for (let index = 2; index < argv.length; index += 1) {
    const arg = argv[index];
    const next = argv[index + 1];

    if (arg === "--supplier-requests") {
      args.supplierRequestsPath = next;
      index += 1;
    } else if (arg === "--email-drafts") {
      args.emailDraftsPath = next;
      index += 1;
    } else if (arg === "--state") {
      args.statePath = next;
      index += 1;
    } else if (arg === "--out-dir") {
      args.outDir = next;
      index += 1;
    } else if (arg === "--summary-only" || arg === "--no-interactive") {
      args.interactive = false;
    } else if (arg === "--help" || arg === "-h") {
      args.help = true;
    } else {
      throw new Error(`Unknown argument: ${arg}`);
    }
  }

  return args;
}

function printHelp() {
  console.log(`Usage:
  track-responses --supplier-requests "path/to/supplier-requests.json" --email-drafts "path/to/email-drafts.md"

Options:
  --supplier-requests  Supplier request JSON generated by the Supplier Request Generator
  --email-drafts       Email draft Markdown generated with the request JSON
  --state              Optional response tracking state JSON
  --out-dir            Tracker export directory, defaults to tools/document-discovery/workbench/exports
  --summary-only       Print summary and write tracker exports without opening the console
  --no-interactive     Same as --summary-only
`);
}

function defaultStatePath({ supplierRequestsPath, outDir }) {
  const baseName = path.basename(supplierRequestsPath, path.extname(supplierRequestsPath));
  return path.join(outDir, `${baseName}-response-state.json`);
}

async function loadState(statePath) {
  try {
    return JSON.parse(await readFile(statePath, "utf8"));
  } catch {
    return {
      created_at: new Date().toISOString(),
      response_tracker: {},
    };
  }
}

async function saveState(statePath, session) {
  session.updated_at = new Date().toISOString();
  await mkdir(path.dirname(statePath), { recursive: true });
  await writeFile(statePath, JSON.stringify(session, null, 2));
}

async function main() {
  const args = parseArgs(process.argv);
  if (args.help || !args.supplierRequestsPath || !args.emailDraftsPath) {
    printHelp();
    process.exitCode = args.help ? 0 : 1;
    return;
  }

  const supplierRequestsPath = path.resolve(args.supplierRequestsPath);
  const emailDraftsPath = path.resolve(args.emailDraftsPath);
  const outDir = path.resolve(args.outDir || path.join(TOOL_ROOT, "workbench", "exports"));
  const statePath = path.resolve(args.statePath || defaultStatePath({ supplierRequestsPath, outDir }));
  const supplierRequests = JSON.parse(await readFile(supplierRequestsPath, "utf8"));
  const emailDraftsText = await readFile(emailDraftsPath, "utf8");
  const session = await loadState(statePath);

  const trackerInput = {
    supplierRequests,
    emailDraftsText,
    session,
    query: supplierRequests.query,
    exportDir: outDir,
  };

  if (args.interactive) {
    await runResponseTrackerConsole({
      ...trackerInput,
      save: () => saveState(statePath, session),
    });
    return;
  }

  const exports = await writeResponseTrackerExports(trackerInput);
  console.log(formatResponseTrackerSummary(buildResponseTrackerModel(trackerInput)));
  console.log(`State file:          ${statePath}`);
  console.log(`Response tracker:    ${exports.jsonPath}`);
  console.log(`Response CSV:        ${exports.csvPath}`);
  console.log(`Follow-up emails:    ${exports.followUpEmailsPath}`);
  console.log(`Gap status summary:  ${exports.gapStatusSummaryPath}`);
}

main().catch((error) => {
  console.error(error instanceof Error ? error.stack : String(error));
  process.exitCode = 1;
});
